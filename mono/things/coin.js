function coinHero(c, mood) {
  // ピカピカ度が下がるほど、くすんだ色になる
  const k = Math.max(0, Math.min(1, (c.cond || 100) / 100));
  const mix = (a, b) => Math.round(b + (a - b) * k);
  const col = `rgb(${mix(234, 176)},${mix(238, 170)},${mix(243, 160)})`;
  return `<circle r="30" fill="${col}" stroke="#9aa4ae" stroke-width="3"/>
    <circle r="24" fill="none" stroke="#c7ced6" stroke-width="2"/>
    <path d="M0 -21 q-5 3 -3 7 q4 -1 3 -7z M0 -21 q5 3 3 7 q-4 -1 -3 -7z" fill="#b8c1ca"/>
    <g transform="translate(0,4)">${face(mood)}</g>`;
}


const RARE_COIN_YEARS = [2011, 2012, 2013, 2016, 2017, 2018, 2019, 2020, 2021, 2022, 2023, 2024, 2025];
function pickCoinYear() {
  // 生まれ年の重み（1989・1990年は消費税で大量に作られた）。年ごとの細かい枚数は演出
  const list = [];
  for (let y = 1955; y <= 2026; y++) {
    let w;
    if (y <= 1966) w = 3; else if (y <= 1988) w = 10; else if (y === 1989) w = 24; else if (y === 1990) w = 28;
    else if (y <= 2000) w = 12; else if (y <= 2010) w = 3; else if (y <= 2013) w = .005; else if (y <= 2015) w = .3;
    else if (y <= 2025) w = .005; else w = 1.3;
    list.push({ y, w });
  }
  return wpick(list).y;
}


